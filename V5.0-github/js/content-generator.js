  /** 从AI返回文本中提取纯名字（处理"名字是：张无道"等格式） */
  _extractName(raw) {
    let text = raw.trim();
    // 常见前缀格式
    const prefixPatterns = [
      /(?:名字|姓名|名称|主角名|character name)\s*[是为：:＝=]\s*/i,
      /^(?:名字|姓名|名称|主角名)\s*[:：]\s*/i,
      /^["""「『]\s*/,
    ];
    for (const p of prefixPatterns) {
      const m = text.match(p);
      if (m) text = text.slice(m[0].length);
    }
    // 常见后缀
    text = text.replace(/\s*[。.！!？?"""」』]\s*$/, '');
    // 提取中文姓名（2-4个汉字）
    const nameMatch = text.match(/[\u4e00-\u9fff]{2,4}/);
    if (nameMatch) return nameMatch[0];
    // 如果全是中文，直接trim
    if (/^[\u4e00-\u9fff]+$/.test(text) && text.length >= 2 && text.length <= 6) return text;
    // 兜底
    return raw.trim();
  },

