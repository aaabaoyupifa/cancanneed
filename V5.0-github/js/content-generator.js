  generate(fieldId, label) {
    const genre = document.getElementById('w-genre').value || '东方玄幻';
    const el = document.getElementById(fieldId);

    const payload = {
      field_id: fieldId,
      genre: genre,
      world_name: document.getElementById('w-name').value.trim(),
      world_desc: document.getElementById('w-desc').value.trim(),
      era: document.getElementById('w-era').value.trim(),
      locations: document.getElementById('w-locations').value.trim(),
      factions: SetupWizard._getFieldValue('w-factions-bulk'),
      power_system: document.getElementById('w-power-system').value.trim(),
      name: document.getElementById('c-name')?.value?.trim() || '',
      sex: document.getElementById('c-sex')?.value || '男',
      age: document.getElementById('c-age')?.value || '',
      personality: document.getElementById('c-personality')?.value?.trim() || '',
      background: document.getElementById('c-background')?.value?.trim() || '',
    };

    // Show loading
    if (el) { el.value = this._randomMsg(); el.style.borderColor = 'var(--ai-color)'; el.style.opacity = '0.7'; el.classList.add('ai-loading'); }

    this._callAPI(payload, fieldId, label, el);
  },

  async _callAPI(payload, fieldId, label, el) {
    if (!AIBridge.isConfigured()) {
      this._fallbackGenerate(fieldId, label, el);
      return;
    }
    try {
      const content = await AIBridge.generate(fieldId, payload);
      if (content) {
        this._fillField(fieldId, content, label, el);
      }
    } catch(e) {
      console.warn('AI API failed, using fallback:', e.message);
      this._fallbackGenerate(fieldId, label, el);
    }
  },

  async _pollForResult(rid, fieldId, label, el) {
    for (let i = 0; i < 30; i++) {
      await new Promise(r => setTimeout(r, 2000));
      try {
        const resp = await fetch(this.API + '/status/' + rid, {signal: AbortSignal.timeout(5000)});
        const data = await resp.json();
        if (data.ready) {
          this._fillField(fieldId, data.content, label, el);
          return;
        }
      } catch(e) { /* retry */ }
      if (el) el.value = `${this._randomMsg()} (${(i+1)*2}s)`;
    }
    throw new Error('poll timeout');
  },

  _fillField(fieldId, content, label, el) {
    if (fieldId === 'w-factions-bulk') {
      SetupWizard._applyFactionsBulk(content);
      el = document.querySelector('#faction-list .faction-item:first-child input');
    }
    // c-name 清理：AI可能返回"名字是：张无道"之类的，提取纯名字
    if (fieldId === 'c-name') {
      content = this._extractName(content);
    }
    if (el) {
      el.classList.remove('ai-loading');
      el.value = content;
      el.style.opacity = '1';
      el.style.borderColor = 'var(--ai-color)';
      setTimeout(() => { el.style.borderColor = ''; }, 2000);
    }
    UIManager.toast(label + ' 已生成！', 'success');
  },

  _fallbackGenerate(fieldId, label, el) {
    // Use template engine as last resort
    const genre = document.getElementById('w-genre').value || '东方玄幻';
    let result = '[生成失败，请重试或手动填写]';
    const g = genre;

    if (fieldId === 'w-desc') result = this._genWorldDesc(g, document.getElementById('w-name').value);
    else if (fieldId === 'w-era') result = this._genEra(g);
    else if (fieldId === 'w-locations') result = this._genLocations(g);
    else if (fieldId === 'w-factions-bulk') result = this._genFactions(g);
    else if (fieldId === 'w-power-system') result = this._genPowerSystem(g);
    else if (fieldId === 'c-name') result = this._genCharName(g, document.getElementById('c-sex').value);
    else if (fieldId === 'c-personality') result = this._genPersonality(g);
    else if (fieldId === 'c-one-line') result = this._genOneLine(g);
    else if (fieldId === 'c-appearance') result = this._genAppearance(g);
    else if (fieldId === 'c-background') result = this._genBackground(g);
    else if (fieldId === 'c-ability') result = this._genAbility(g);
    else if (fieldId === 'c-goal') result = this._genGoal(g);

    this._fillField(fieldId, result, label + '（备用模板）', el);
  },

